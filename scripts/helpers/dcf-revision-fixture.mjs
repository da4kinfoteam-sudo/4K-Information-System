export async function insertParent(db, domain, overrides = {}) {
    assert.ok(domains.includes(domain), 'Only the five fixed DCF domains can be inserted');
    const record = { uid: `FIXTURE-${domain.type}-${crypto.randomUUID()}`, operatingUnit: 'RFO I',
        encodedBy: 'Legacy encoder', fundType: 'Current', tier: 'Tier 1', fundSourceUid: 'FS-000001',
        fundSource: '4K Fund', [domain.label]: `DCF ${domain.type} A`, ...overrides };
    if (domain.lines && !(domain.lines in record)) record[domain.lines] = [plannedLine()];
    if (domain.table === 'staffing_requirements') record.hiringStatus ??= 'Proposed';
    else record.status ??= 'Proposed';
    const fields = Object.keys(record);
    return (await db.query(`insert into ${quote(domain.table)}(${fields.map(quote).join(',')})
      values(${fields.map((_, i) => `$${i + 1}`).join(',')}) returning *`,
    fields.map(k => typeof record[k] === 'object' && record[k] !== null ? JSON.stringify(record[k]) : record[k]))).rows[0];
}

