export async function rows(db, table) {
    return (await db.query(`select to_jsonb(t) as row from public.${quote(table)} t order by to_jsonb(t)::text`)).rows.map(r => r.row);
}

export async function fingerprints(db, tableNames) {
    const tables = tableNames || (await db.query(`select tablename from pg_tables where schemaname='public' order by tablename`)).rows.map(r => r.tablename);
    const result = {};
    for (const table of tables) result[table] = await rows(db, table);
    return result;
}

export async function securityFingerprint(db) {
    return {
        tables: (await db.query(`select c.relname,c.relowner::regrole::text,c.relacl::text,c.relrowsecurity,c.relforcerowsecurity
          from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relkind in ('r','S') order by c.relname`)).rows,
        functions: (await db.query(`select p.proname,pg_get_function_identity_arguments(p.oid) as args,
          p.proowner::regrole::text,p.proacl::text,p.prosecdef,p.provolatile,p.proconfig
          from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' order by p.proname,args`)).rows,
        policies: (await db.query(`select schemaname,tablename,policyname,permissive,roles,cmd,qual,with_check from pg_policies
          where schemaname='public' order by tablename,policyname`)).rows,
    };
}

const rpcNames = new Set(['read_dcf_state', 'commit_dcf_change', 'list_dcf_revisions', 'read_dcf_revision',
    'preview_dcf_restore', 'apply_dcf_restore', 'undo_dcf_restore', 'dcf_revision_capability', 'delete_dcf_record']);
// Named arguments and catalog casts keep JSON, UUID and text[] distinct. The
// allowlist prevents this helper from becoming a generic untrusted SQL runner.
export async function rpc(db, name, args) {
    assert.ok(rpcNames.has(name), `Unsupported fixture RPC: ${name}`);
    const candidates = (await db.query(`select p.oid,p.proargnames as names,
      array(select format_type(t,null) from unnest(p.proargtypes::oid[]) t) as types,
      p.pronargs-p.pronargdefaults as required
      from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname=$1`, [name])).rows;
    const provided = Object.keys(args);
    const matching = candidates.filter(c => provided.every(k => c.names.includes(k)) && c.names.slice(0, c.required).every(k => provided.includes(k)));
    assert.equal(matching.length, 1, `RPC ${name} arguments do not match exactly one installed signature: ${JSON.stringify(candidates)}`);
    const spec = matching[0];
    const values = provided.map(k => ['json', 'jsonb'].includes(spec.types[spec.names.indexOf(k)]) ? JSON.stringify(args[k]) : args[k]);
    return (await db.query(`select public.${quote(name)}(${provided.map((k, i) => `${quote(k)} => $${i + 1}::${spec.types[spec.names.indexOf(k)]}`).join(',')}) as data`, values)).rows[0].data;
}

export async function transaction(db, action) {
    await db.exec('begin');
    try { const result = await action(); await db.exec('commit'); return result; }
    catch (error) { await db.exec('rollback'); throw error; }
}
