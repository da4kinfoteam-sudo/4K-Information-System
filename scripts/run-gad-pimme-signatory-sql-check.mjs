import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import path from 'node:path';
const require = createRequire(path.join(process.env.PGLITE_RUNTIME || path.join(tmpdir(), '4kis-supplement-sql-runtime'), 'package.json'));
const { PGlite } = require('@electric-sql/pglite');
const db = new PGlite();
try {
    await db.exec(`create role anon; create role authenticated; create role service_role;
      create table users(id bigint primary key, role text, "operatingUnit" text, "fullName" text, permissions_override jsonb, visibility_scope text);
      create table roles_config(role text,module text,can_view boolean,can_edit boolean,can_delete boolean,can_manage boolean,visibility_scope text);
      create table google_drive_connections(id uuid primary key);
      insert into users values(1,'Super Admin','NPMO','Admin','{}','All OUs'),(2,'User','RPMO 1','Editor','{}','Own OU'),(3,'Guest','RPMO 1','Viewer','{}','Own OU');
      insert into roles_config values('Super Admin','Gender and Development',true,true,true,true,'All OUs'),('User','Gender and Development',true,true,false,false,'Own OU'),('Guest','Gender and Development',true,false,false,false,'Own OU');`);
    await db.exec(await readFile('supabase/migrations/202608050001_gad_pimme_assessments.sql', 'utf8'));
    const oldSave = async (ou, year, answers, actor = 1) => (await db.query('select to_jsonb(save_gad_pimme_assessment($1,$2,$3,$4,$5)) as row', [ou, year, JSON.stringify(answers), actor, 'Fixture'])).rows[0].row;
    const answer = [{ question_key: 'box16-1.1', response: 'Yes', remarks: 'Preserve this' }];
    const legacy = await oldSave('RPMO 1', 2025, answer);
    const beforeAnswers = (await db.query('select * from gad_pimme_answers')).rows;
    const migration = await readFile('supabase/migrations/202610150001_gad_pimme_signatories.sql', 'utf8');
    await db.exec(migration); await db.exec(migration);
    const after = (await db.query('select to_jsonb(a) as row from gad_pimme_assessments a where id=$1', [legacy.id])).rows[0].row;
    for (const key of Object.keys(after).filter(key => !(key in legacy))) { assert.equal(after[key], null); delete after[key]; }
    assert.deepEqual(after, legacy, 'Installing migration leaves all existing business values/timestamps unchanged');
    assert.deepEqual((await db.query('select * from gad_pimme_answers')).rows, beforeAnswers);
    const save = async (ou, year, answers, fields, actor = 1) => (await db.query('select to_jsonb(save_gad_pimme_assessment($1,$2,$3,$4,$5,$6)) as row', [ou, year, JSON.stringify(answers), actor, 'Fixture', JSON.stringify(fields)])).rows[0].row;
    let saved = await save('RPMO 1', 2025, answer, { prepared_by_name: ' Staff ', prepared_by_position: 'Officer', reviewed_by_name: 'Reviewer', approved_by_name: 'Approver' }, 2);
    assert.equal(saved.prepared_by_name, 'Staff'); assert.equal(saved.prepared_by_position, 'Officer');
    assert.equal(Number(saved.total_score), 1); assert.equal(saved.answered_count, 1); assert.equal(saved.status, 'Incomplete');
    saved = await oldSave('RPMO 1', 2025, answer, 2);
    assert.equal(saved.prepared_by_name, 'Staff', 'Old client save preserves signatories');
    saved = await save('RPMO 1', 2025, answer, {}, 2);
    assert.equal(saved.prepared_by_name, 'Staff', 'Omitted properties preserve values');
    saved = await save('RPMO 1', 2025, answer, { prepared_by_name: null, prepared_by_position: '  ' }, 2);
    assert.equal(saved.prepared_by_name, null); assert.equal(saved.prepared_by_position, null);
    assert.equal(saved.reviewed_by_name, 'Reviewer');
    const snapshot = async () => (await db.query('select to_jsonb(a) as row from gad_pimme_assessments a order by id')).rows;
    const beforeFailure = await snapshot();
    await assert.rejects(() => save('RPMO 1', 2025, [{ question_key: 'bad', response: 'Yes' }], { approved_by_name: 'Must rollback' }), /Unknown PIMME/);
    assert.deepEqual(await snapshot(), beforeFailure, 'Failed answer validation rolls back signatories, answers and metadata');
    await assert.rejects(() => save('RPMO 1', 2025, answer, { status: 'Completed' }), /Unknown signatory/);
    await assert.rejects(() => save('RPMO 1', 2025, answer, { prepared_by_name: 10 }), /text or null/);
    await assert.rejects(() => save('NPMO', 2025, answer, {}, 2), /outside.*visibility/);
    await assert.rejects(() => save('RPMO 1', 2025, answer, {}, 3), /permission to edit/);
    assert.equal((await save('NPMO', 2025, answer, { approved_by_name: 'National' })).approved_by_name, 'National');
    assert.equal((await save('RPMO 1', 2024, answer, {})).reviewed_by_name, null, 'Signatories never leak across years');
    await db.exec('set role anon');
    await assert.rejects(() => db.exec("update gad_pimme_assessments set approved_by_name='Bypass'"), /permission denied/);
    assert.equal((await oldSave('RPMO 1', 2025, answer)).reviewed_by_name, 'Reviewer');
    assert.equal((await save('RPMO 1', 2025, answer, { approved_by_position: 'Director' })).approved_by_position, 'Director');
    console.log('GAD PIMME signatory migration, permissions, legacy compatibility and atomic rollback checks passed (isolated PGlite only).');
} finally { await db.close(); }
