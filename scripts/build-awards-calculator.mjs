import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {bundleAwardsCalculator,root} from './helpers/awards-calculator-bundle.mjs';
const {code,sourceHash}=await bundleAwardsCalculator();
const output=path.join(root,'supabase/functions/_shared/awardsCalculator.generated.mjs');
const contents=`// Generated by scripts/build-awards-calculator.mjs. Do not edit.\n// Source SHA256: ${sourceHash}\n${code}\nexport const awardsCalculatorSourceHash = '${sourceHash}';\n`;
if(process.argv.includes('--check')){
    if(await readFile(output,'utf8').catch(()=>null)!==contents)throw new Error('The trusted Awards calculator bundle is stale. Run npm run build:awards-calculator.');
    console.log('Trusted Awards calculator source hash and generated bundle match.');
}else{
    await writeFile(output,contents);console.log(`Generated trusted Awards calculator (${contents.length} bytes; source ${sourceHash}).`);
}
