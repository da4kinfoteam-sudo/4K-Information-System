import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';

// The only remote operation is a read-only schema-catalog query. All fixtures
// and transfer calls run in an ephemeral local PostgreSQL-compatible database.
const [runtimeRoot, schemaWorkdir] = process.argv.slice(2);
if (!runtimeRoot || !schemaWorkdir) throw new Error('Supply the PGlite runtime directory and linked schema checkout.');
const require = createRequire(`${runtimeRoot.replaceAll('\\', '/')}/package.json`);
const { PGlite } = require('@electric-sql/pglite');
const query = `select table_name,column_name,data_type,column_default,is_nullable from information_schema.columns
  where table_schema='public' and table_name in ('users','roles_config','subprojects','activities',
  'financial_obligations','financial_disbursements','subproject_accomplishments','budget_item_adjustment_history')
  order by table_name,ordinal_position`;
const output = execFileSync('powershell.exe', ['-NoProfile', '-Command',
  'supabase db query --linked --output json $env:TRANSFER_SCHEMA_QUERY'], {
  cwd: schemaWorkdir, encoding: 'utf8', env: { ...process.env, TRANSFER_SCHEMA_QUERY: query },
});
const columns = JSON.parse(output).rows;
const quote = value => `"${value.replaceAll('"', '""')}"`;
const db = new PGlite();
try {
  await db.exec(`create role anon; create role authenticated; create schema auth;
    create function auth.uid() returns uuid language sql as $$ select null::uuid $$;`);
  for (const table of [...new Set(columns.map(column => column.table_name))]) {
    const definitions = columns.filter(column => column.table_name === table).map(column => {
      let declaration = `${quote(column.column_name)} ${column.data_type}`;
      if (column.column_name === 'id') return `${declaration} generated by default as identity primary key`;
      if (column.column_default && !column.column_default.includes('nextval(')) declaration += ` default ${column.column_default}`;
      if (column.is_nullable === 'NO') declaration += ' not null';
      return declaration;
    });
    await db.exec(`create table public.${quote(table)} (${definitions.join(',')});`);
  }
  await db.exec(`insert into users (id,username,"fullName",role,"operatingUnit",password,visibility_scope,requires_approver,approver_id)
    values (1,'admin','Synthetic Admin','Super Admin','NPMO','fixture-password','All OUs',false,null),
    (2,'pending','Synthetic Requester','Administrator','RFO I','fixture-password','Own OU',true,1),
    (3,'denied','Synthetic Viewer','User','RFO I','fixture-password','Own OU',false,null);
    insert into roles_config (role,module,can_view,can_edit) values
    ('Super Admin','Subprojects',true,true),('Super Admin','Activities',true,true),
    ('Administrator','Subprojects',true,true),('User','Subprojects',true,false);`);
  const migration = readFileSync(new URL('../supabase/migrations/202610090001_activity_subproject_budget_item_transfers.sql', import.meta.url), 'utf8');
  await db.exec(`insert into subprojects (name,status,"operatingUnit",details) values ('Unchanged legacy row','Proposed','NPMO','[]');
    insert into activities (name,status,"operatingUnit",expenses) values ('Unchanged legacy activity','Proposed','NPMO','[]');`);
  const originalSubproject = (await db.query('select to_jsonb(record_value) as record from subprojects record_value')).rows[0].record;
  await db.exec(`begin; ${migration} commit;`);
  const afterMigration = (await db.query(`select to_jsonb(record_value) - 'isTransferTargetExcluded' - 'budgetItemTransferId' as record
    from subprojects record_value where id=$1`, [originalSubproject.id])).rows[0].record;
  assert.deepEqual(afterMigration, originalSubproject);
  assert.equal((await db.query('select count(*)::int as count from budget_item_transfers')).rows[0].count, 0);
  await db.exec(`update roles_config set can_transfer_budget_items=true where role='Administrator';`);
  const actualKeys = {
    subproject: ['actualMaleBeneficiaries','actualFemaleBeneficiaries','actualFourPsBeneficiaries','actualPWD','actualMuslim','actualLGBTQ','actualSoloParent','actualSenior','actualYouth'],
    activity: ['actualParticipantsMale','actualParticipantsFemale','actualPWD','actualMuslim','actualLGBTQ','actualSoloParent','actualSenior','actualYouth'],
  };
  const insertSource = async (type, status = 'Completed') => {
    const table = type === 'subproject' ? 'subprojects' : 'activities';
    const lineColumn = type === 'subproject' ? 'details' : 'expenses';
    const lines = [{ id: 101, particulars: 'Selected', amount: 100 }, { id: 102, particulars: 'Retained', amount: 200 }];
    const result = await db.query(`insert into ${table} (name,status,"operatingUnit",${quote(lineColumn)},workflow_status,updated_at)
      values ('Synthetic source',$1,'RFO I',$2,'APPROVED',now()) returning *`, [status, JSON.stringify(lines)]);
    return result.rows[0];
  };
  const submit = async (type, source, actorId = 1, requestKey = crypto.randomUUID(), metadata = {}) => {
    const allocation = Object.fromEntries(actualKeys[type].map(key => [key, source[key] ?? null]));
    const destination = Object.fromEntries(actualKeys[type].map(key => [key, source[key] == null ? null : 0]));
    const result = await db.query(`select submit_budget_item_transfer($1,'fixture-password',$2,$3,array['101'],
      $4::jsonb,$5::jsonb,$6::jsonb,'Synthetic test',$7::uuid) as result`,
      [actorId, type, source.id, JSON.stringify(metadata), JSON.stringify(destination), JSON.stringify(allocation), requestKey]);
    return result.rows[0].result;
  };
  for (const type of ['subproject', 'activity']) {
    const source = await insertSource(type);
    const entity = type === 'subproject' ? 'subproject_detail' : 'activity_expense';
    await db.query(`insert into financial_obligations (entity_type,parent_id,item_id,obligation_date,amount)
      values ($1,$2,'101','2026-10-01',80),($1,$2,'102','2026-10-01',160)`, [entity, source.id]);
    await db.query(`insert into financial_disbursements (entity_type,parent_id,item_id,disbursement_date,amount)
      values ($1,$2,'101','2026-10-01',40)`, [entity, source.id]);
    if (type === 'subproject') await db.query(`insert into subproject_accomplishments (subproject_id,detail_id,quantity) values ($1,101,1)`, [source.id]);
    const key = crypto.randomUUID();
    const result = await submit(type, source, 1, key);
    assert.equal(result.status, 'applied');
    const lineColumn = type === 'subproject' ? 'details' : 'expenses';
    assert.deepEqual(result.source[lineColumn].map(line => line.id), [102]);
    assert.deepEqual(result.destination[lineColumn].map(line => line.id), [101]);
    assert.equal(result.source[actualKeys[type][0]], null);
    assert.equal(result.destination[actualKeys[type][0]], null);
    assert.equal(result.destination.isTransferTargetExcluded, true);
    assert.equal((await db.query(`select parent_id from financial_obligations where entity_type=$1 and item_id='101'`, [entity])).rows[0].parent_id, result.destination.id);
    assert.equal((await db.query(`select parent_id from financial_obligations where entity_type=$1 and item_id='102'`, [entity])).rows[0].parent_id, source.id);
    assert.equal((await db.query(`select parent_id from financial_disbursements where entity_type=$1 and item_id='101'`, [entity])).rows[0].parent_id, result.destination.id);
    if (type === 'subproject') assert.equal((await db.query(`select subproject_id from subproject_accomplishments where detail_id=101`)).rows[0].subproject_id, result.destination.id);
    assert.equal((await submit(type, source, 1, key)).destination.id, result.destination.id);
  }
  const pendingSource = await insertSource('subproject');
  const pending = await submit('subproject', pendingSource, 2);
  assert.equal(pending.status, 'pending');
  assert.equal(pending.source.details.length, 2);
  const approved = (await db.query(`select resolve_budget_item_transfer(1,'fixture-password',$1,'approve',null) as result`, [pending.transfer_id])).rows[0].result;
  assert.equal(approved.status, 'applied');
  assert.equal(approved.source.details.length, 1);
  const rejectedSource = await insertSource('subproject');
  const pendingReject = await submit('subproject', rejectedSource, 2);
  const rejected = (await db.query(`select resolve_budget_item_transfer(1,'fixture-password',$1,'reject','Not approved') as result`, [pendingReject.transfer_id])).rows[0].result;
  assert.equal(rejected.status, 'rejected');
  assert.equal(rejected.source.details.length, 2);
  const deniedSource = await insertSource('subproject');
  await assert.rejects(submit('subproject', deniedSource, 3), /permission/);
  await assert.rejects(submit('subproject', await insertSource('subproject', 'Cancelled')), /Cancelled/);
  await db.exec(`reset app.allow_budget_item_transfer_resolution;`);
  await assert.rejects(db.query(`update subprojects set "isTransferTargetExcluded"=true where id=$1`, [deniedSource.id]), /classification/);
  console.log('SQL transfer checks passed: apply, retry, null actuals, selected-row reparenting, approval, rejection, permissions and cancellation. No remote business records were written.');
} finally {
  await db.close();
}
