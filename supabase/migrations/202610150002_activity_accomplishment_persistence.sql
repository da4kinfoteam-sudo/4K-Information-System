-- Additive only: no existing Activity or financial records are rewritten.
begin;
set local lock_timeout='5s';
lock table public.activities,public.financial_obligations,public.financial_disbursements in share mode;
do $$
declare fingerprints jsonb;
begin
  select jsonb_object_agg(table_name,signature) into fingerprints from (
    select 'activities' as table_name,jsonb_build_object('count',count(*),'digest',md5(coalesce(string_agg(md5(to_jsonb(r)::text),'' order by id),''))) as signature from public.activities r
    union all select 'financial_obligations',jsonb_build_object('count',count(*),'digest',md5(coalesce(string_agg(md5(to_jsonb(r)::text),'' order by id),''))) from public.financial_obligations r
    union all select 'financial_disbursements',jsonb_build_object('count',count(*),'digest',md5(coalesce(string_agg(md5(to_jsonb(r)::text),'' order by id),''))) from public.financial_disbursements r
  ) signatures;
  perform set_config('app.activity_actuals_install_fingerprints',fingerprints::text,true);
end; $$;
create table if not exists public.activity_financial_entry_state (
  activity_id bigint not null references public.activities(id) on delete cascade,
  item_id text not null,
  stage text not null check(stage in ('obligation','disbursement')),
  primary key(activity_id,item_id,stage)
);
create table if not exists public.activity_accomplishment_requests (
  request_key uuid primary key, activity_id bigint not null references public.activities(id),
  actor_id bigint not null references public.users(id), request_hash text not null,
  response jsonb not null, created_at timestamptz not null default now()
);
create table if not exists public.activity_accomplishment_revisions (
  id bigint generated by default as identity primary key,
  activity_id bigint not null references public.activities(id), actor_id bigint references public.users(id),
  request_key uuid not null, reason text, changes jsonb not null,
  created_at timestamptz not null default now()
);
alter table public.activity_financial_entry_state enable row level security;
alter table public.activity_accomplishment_requests enable row level security;
alter table public.activity_accomplishment_revisions enable row level security;
revoke all on public.activity_financial_entry_state,public.activity_accomplishment_requests,public.activity_accomplishment_revisions from anon,authenticated;
grant all on public.activity_financial_entry_state,public.activity_accomplishment_requests,public.activity_accomplishment_revisions to service_role;

-- Records that have used the central ledger must never fall back to stale JSON
-- after the last explicit deletion. The trigger also serializes old/new writers.
create or replace function public.track_activity_financial_entry_state() returns trigger
language plpgsql security definer set search_path=public,pg_temp as $$
declare stage_value text;
begin
  stage_value:=case when tg_table_name='financial_obligations' then 'obligation' else 'disbursement' end;
  if tg_op in ('UPDATE','DELETE') and old.entity_type='activity_expense' then
    perform id from public.activities where id=old.parent_id for update;
    if found and old.item_id is not null then
      insert into public.activity_financial_entry_state values(old.parent_id,old.item_id::text,stage_value) on conflict do nothing;
    end if;
  end if;
  if tg_op in ('INSERT','UPDATE') and new.entity_type='activity_expense' then
    perform id from public.activities where id=new.parent_id for update;
    if found and new.item_id is not null then
      insert into public.activity_financial_entry_state values(new.parent_id,new.item_id::text,stage_value) on conflict do nothing;
    end if;
  end if;
  if tg_op='DELETE' then return old; end if;
  return new;
end; $$;
drop trigger if exists track_activity_financial_entry_state on public.financial_obligations;
create trigger track_activity_financial_entry_state before insert or update or delete on public.financial_obligations for each row execute function public.track_activity_financial_entry_state();
drop trigger if exists track_activity_financial_entry_state on public.financial_disbursements;
create trigger track_activity_financial_entry_state before insert or update or delete on public.financial_disbursements for each row execute function public.track_activity_financial_entry_state();

create or replace function public.activity_accomplishment_actor(p_actor_id bigint,p_password text,p_activity_id bigint,p_surface text)
returns public.users language plpgsql security definer set search_path=public,pg_temp as $$
declare a public.users%rowtype; r public.roles_config%rowtype; parent public.activities%rowtype; module_name text; scope_value text; v jsonb;
begin
  if p_surface is null or p_surface not in ('activity','financial') then raise exception 'Invalid accomplishment entry surface.'; end if;
  select * into a from public.users where id=p_actor_id;
  if a.id is null or a.role is null then raise exception 'Your session could not be verified.' using errcode='42501'; end if;
  if auth.uid() is not null then
    if a.auth_id is distinct from auth.uid() then raise exception 'Your session does not match this request.' using errcode='42501'; end if;
  elsif nullif(p_password,'') is null or a.password is distinct from p_password then
    raise exception 'Your session could not be verified.' using errcode='42501';
  end if;
  module_name:=case when p_surface='activity' then 'Activities' else 'Accomplishment - Financial' end;
  select * into r from public.roles_config where role=a.role and module=module_name limit 1;
  v:=a.permissions_override->module_name->'can_view';
  if a.role not in ('Super Admin','Administrator') and not(case when jsonb_typeof(v)='boolean' then (v#>>'{}')::boolean else coalesce(r.can_view,true) end) then
    raise exception 'You do not have permission to view these accomplishments.' using errcode='42501';
  end if;
  select * into parent from public.activities where id=p_activity_id;
  if parent.id is null then raise exception 'The Activity is no longer available.' using errcode='P0002'; end if;
  scope_value:=case when a.visibility_scope in ('Own OU','All OUs') then a.visibility_scope
    when r.visibility_scope in ('Own OU','All OUs') then r.visibility_scope
    when a.role in ('Super Admin','Administrator','Management') then 'All OUs' else 'Own OU' end;
  if scope_value='Own OU' and parent."operatingUnit" is distinct from a."operatingUnit" then raise exception 'The Activity is outside your OU scope.' using errcode='42501'; end if;
  return a;
end; $$;

create or replace function public.activity_financial_stage(p_parent jsonb,p_item_id text,p_stage text)
returns jsonb language plpgsql volatile security definer set search_path=public,pg_temp as $$
declare result jsonb; line jsonb; arr jsonb; array_key text; amount_key text; date_key text;
begin
  if p_stage not in ('obligation','disbursement') then raise exception 'Invalid financial stage.'; end if;
  if p_stage='obligation' then
    select jsonb_agg(jsonb_build_object('id',id::text,'date',obligation_date::text,'amount',amount,'remarks',coalesce(remarks,'')) order by id) into result
      from public.financial_obligations where entity_type='activity_expense' and parent_id=(p_parent->>'id')::bigint and item_id::text=p_item_id;
  else
    select jsonb_agg(jsonb_build_object('id',id::text,'date',disbursement_date::text,'amount',amount,'remarks',coalesce(remarks,'')) order by id) into result
      from public.financial_disbursements where entity_type='activity_expense' and parent_id=(p_parent->>'id')::bigint and item_id::text=p_item_id;
  end if;
  if result is not null or exists(select 1 from public.activity_financial_entry_state where activity_id=(p_parent->>'id')::bigint and item_id=p_item_id and stage=p_stage) then
    return jsonb_build_object('source','central','entries',coalesce(result,'[]'::jsonb));
  end if;
  select value into line from jsonb_array_elements(coalesce(nullif(p_parent->'expenses','null'::jsonb),'[]'::jsonb)) where value->>'id'=p_item_id;
  array_key:=case when p_stage='obligation' then 'obligations' else 'disbursements' end;
  amount_key:=case when p_stage='obligation' then 'actualObligationAmount' else 'actualDisbursementAmount' end;
  date_key:=case when p_stage='obligation' then 'actualObligationDate' else 'actualDisbursementDate' end;
  arr:=coalesce(nullif(line->array_key,'null'::jsonb),'[]'::jsonb);
  if jsonb_array_length(arr)=0 and coalesce((line->>amount_key)::numeric,0)<>0 then
    arr:=jsonb_build_array(jsonb_build_object('date',coalesce(line->>date_key,''),'amount',(line->>amount_key)::numeric,'remarks','Legacy Record'));
  end if;
  select coalesce(jsonb_agg(jsonb_build_object('id','legacy:'||p_stage||':'||p_item_id||':'||(ordinality-1)::text,
    'date',coalesce(value->>'date',''),'amount',coalesce((value->>'amount')::numeric,0),'remarks',coalesce(value->>'remarks','')) order by ordinality),'[]'::jsonb)
    into result from jsonb_array_elements(arr) with ordinality;
  return jsonb_build_object('source','legacy','entries',result);
end; $$;

create or replace function public.activity_accomplishment_snapshot(p_parent jsonb) returns jsonb
language plpgsql volatile security definer set search_path=public,pg_temp as $$
declare stages jsonb:='{}'; line jsonb; item_id text;
begin
  if exists(select 1 from jsonb_array_elements(coalesce(nullif(p_parent->'expenses','null'::jsonb),'[]'::jsonb)) e group by e->>'id' having e->>'id' is null or count(*)>1) then raise exception 'Expense identities are ambiguous. No changes were saved.'; end if;
  for line in select value from jsonb_array_elements(coalesce(nullif(p_parent->'expenses','null'::jsonb),'[]'::jsonb)) loop
    item_id:=line->>'id';
    stages:=stages||jsonb_build_object(item_id,jsonb_build_object('obligation',public.activity_financial_stage(p_parent,item_id,'obligation'),'disbursement',public.activity_financial_stage(p_parent,item_id,'disbursement')));
  end loop;
  return jsonb_build_object('activity',p_parent,'stages',stages);
end; $$;

create or replace function public.read_activity_accomplishments(p_actor_id bigint,p_actor_password text,p_activity_ids bigint[],p_surface text)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare parent public.activities%rowtype; result jsonb:='[]'; id_value bigint;
begin
  if coalesce(array_length(p_activity_ids,1),0)>100 then raise exception 'Load at most 100 scoped Activities at a time.'; end if;
  for id_value in select distinct unnest(p_activity_ids) order by 1 loop
    perform public.activity_accomplishment_actor(p_actor_id,p_actor_password,id_value,p_surface);
    select * into parent from public.activities where id=id_value for share;
    perform public.activity_accomplishment_actor(p_actor_id,p_actor_password,id_value,p_surface);
    result:=result||jsonb_build_array(public.activity_accomplishment_snapshot(to_jsonb(parent)));
  end loop;
  return result;
end; $$;

create or replace function public.check_activity_accomplishment_policy(p_actor public.users,p_parent public.activities,p_action text,p_month text,p_reason text)
returns void language plpgsql security definer set search_path=public,pg_temp as $$
declare settings jsonb; overrides jsonb; is_override boolean; allowed boolean; module_name text; v jsonb; rule public.roles_config%rowtype;
begin
  select s.settings into settings from public.dcf_policy_settings s where settings_key='dcf_editing_policy';
  settings:=coalesce(settings,'{}');
  overrides:=coalesce(settings->'monthLock'->'overrideRoles','["Super Admin","Administrator"]');
  is_override:=overrides ? p_actor.role;
  module_name:=case when p_action='editBudget' then 'Activities' when p_action='editPhysicalAccomplishment' then 'Accomplishment - Physical' else 'Accomplishment - Financial' end;
  if p_actor.role='Guest' then raise exception 'Guest users cannot change accomplishments.' using errcode='42501'; end if;
  select * into rule from public.roles_config where role=p_actor.role and module=module_name limit 1;
  v:=p_actor.permissions_override->module_name->'can_edit';
  allowed:=case when p_actor.role in ('Super Admin','Administrator') then true when jsonb_typeof(v)='boolean' then (v#>>'{}')::boolean else coalesce(rule.can_edit,false) end;
  if not is_override and not allowed then raise exception 'Accomplishment edit permission is required.' using errcode='42501'; end if;
  v:=settings->'roleRules'->p_actor.role->'activities'->p_parent.status->p_action;
  allowed:=case when jsonb_typeof(v)='boolean' then (v#>>'{}')::boolean else p_parent.status=case when p_action='editBudget' then 'Proposed' else 'Ongoing' end or p_actor.role in ('Super Admin','Administrator') end;
  if not is_override and not allowed then raise exception 'Accomplishment editing is locked for this role and status.' using errcode='42501'; end if;
  if is_override and coalesce((settings->'monthLock'->>'requireOverrideReason')::boolean,true) and nullif(btrim(p_reason),'') is null then
    raise exception 'An override reason is required.' using errcode='42501';
  end if;
  -- As in the current UI, an amount-only correction retains its encoded month.
  if p_month is not null and coalesce((settings->'monthLock'->>'enabled')::boolean,true) then
    if p_month !~ '^\d{4}-\d{2}-\d{2}$' then raise exception 'A valid accomplishment date is required.'; end if;
    if not is_override and date_trunc('month',p_month::date)<>date_trunc('month',now() at time zone 'Asia/Manila') then
      raise exception 'Only the current accomplishment month is open.' using errcode='42501';
    end if;
  end if;
end; $$;

create or replace function public.save_activity_accomplishment(
  p_actor_id bigint,p_actor_password text,p_activity_id bigint,p_surface text,
  p_base jsonb,p_edits jsonb,p_physical jsonb,p_reason text,p_request_key uuid,p_targets jsonb default '[]'::jsonb
) returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare
  actor public.users%rowtype; parent public.activities%rowtype; cached public.activity_accomplishment_requests%rowtype;
  before_parent jsonb; result jsonb; fingerprint text; edit jsonb; op jsonb; baseline jsonb; current_stage jsonb;
  item_id text; stage_value text; table_name text; date_column text; entry jsonb; previous jsonb; intended jsonb; maps jsonb;
  entry_id bigint; new_id bigint; line jsonb; output_lines jsonb; stage_rows jsonb; total numeric; last_date text;
  changed_stages jsonb:='{}'; touched boolean:=false; field text; physical_value jsonb; physical_before jsonb; physical_current jsonb;
  before_changes jsonb:='[]'; after_changes jsonb:='[]'; physical_audit_before jsonb:='{}'; entry_date text; entry_amount numeric; target_edits jsonb:='{}'; target_base jsonb;
begin
  actor:=public.activity_accomplishment_actor(p_actor_id,p_actor_password,p_activity_id,p_surface);
  if p_request_key is null or jsonb_typeof(p_edits) is distinct from 'array' or jsonb_typeof(p_physical) is distinct from 'object' or jsonb_typeof(p_base) is distinct from 'object' or jsonb_typeof(p_targets) is distinct from 'array' then raise exception 'An explicit accomplishment draft and request key are required.'; end if;
  fingerprint:=md5(jsonb_build_object('base',p_base,'edits',p_edits,'physical',p_physical,'reason',p_reason,'surface',p_surface,'targets',p_targets)::text);
  select * into parent from public.activities where id=p_activity_id for update;
  actor:=public.activity_accomplishment_actor(p_actor_id,p_actor_password,p_activity_id,p_surface);
  select * into cached from public.activity_accomplishment_requests where request_key=p_request_key;
  if cached.request_key is not null then
    if cached.activity_id<>p_activity_id or cached.actor_id<>actor.id or cached.request_hash<>fingerprint then raise exception 'This request key belongs to a different draft.'; end if;
    return cached.response;
  end if;
  before_parent:=to_jsonb(parent);
  if (p_base->'activity'->>'id')::bigint is distinct from parent.id then raise exception 'The accomplishment baseline does not belong to this Activity.'; end if;
  foreach field in array array['status','workflow_status','operatingUnit','type','budgetItemTransferId'] loop
    if before_parent->field is distinct from p_base->'activity'->field then raise exception 'The Activity identity or workflow changed. Reopen before saving.' using errcode='40001'; end if;
  end loop;
  if parent."budgetItemTransferId" is not null and parent.workflow_status is distinct from 'APPROVED' then raise exception 'This transfer is not approved.' using errcode='42501'; end if;
  if exists(select 1 from jsonb_array_elements(p_edits) e group by e->>'itemId',e->>'stage' having count(*)>1) then raise exception 'Duplicate financial stages in this request.'; end if;
  -- Existing Financial ACF target inputs remain explicit Proposed-only edits.
  for edit in select value from jsonb_array_elements(p_targets) loop
    if p_surface<>'financial' or parent.status<>'Proposed' then raise exception 'Target changes require the existing Proposed budget flow.'; end if;
    perform public.check_activity_accomplishment_policy(actor,parent,'editBudget',null,p_reason);
    item_id:=edit->>'itemId';
    if item_id is null or target_edits ? item_id or jsonb_typeof(edit->'values') is distinct from 'object' then raise exception 'Invalid target change.'; end if;
    select value into line from jsonb_array_elements(parent.expenses) where value->>'id'=item_id;
    select value into target_base from jsonb_array_elements(p_base->'activity'->'expenses') where value->>'id'=item_id;
    if line is null or target_base is null then raise exception 'The target expense changed. Reopen before saving.' using errcode='40001'; end if;
    for field,physical_value in select * from jsonb_each(edit->'values') loop
      if field not in ('amount','obligationMonth','disbursementMonth') then raise exception 'Invalid target field.'; end if;
      if coalesce(nullif(line->field,'null'::jsonb),'null'::jsonb) is distinct from coalesce(nullif(target_base->field,'null'::jsonb),'null'::jsonb) then raise exception 'The target changed while editing.' using errcode='40001'; end if;
      if field='amount' then
        if physical_value='null'::jsonb or (physical_value#>>'{}')::numeric<0 or (physical_value#>>'{}')::numeric::text in ('NaN','Infinity','-Infinity') then raise exception 'Target amounts must be non-negative.'; end if;
      elsif nullif(physical_value#>>'{}','') is not null then perform (physical_value#>>'{}')::date; end if;
    end loop;
    target_edits:=target_edits||jsonb_build_object(item_id,edit->'values'); touched:=true;
  end loop;
  for edit in select value from jsonb_array_elements(p_edits) loop
    item_id:=edit->>'itemId'; stage_value:=edit->>'stage';
    if stage_value is null or stage_value not in ('obligation','disbursement') or jsonb_typeof(edit->'operations') is distinct from 'array' then raise exception 'Invalid financial change.'; end if;
    if jsonb_array_length(edit->'operations')=0 then continue; end if;
    perform public.check_activity_accomplishment_policy(actor,parent,'editFinancialAccomplishment',null,p_reason);
    select value into line from jsonb_array_elements(coalesce(nullif(parent.expenses,'null'::jsonb),'[]'::jsonb)) where value->>'id'=item_id;
    if line is null or coalesce((line->>'isCancelled')::boolean,false) or coalesce((line->>'isSuperseded')::boolean,false) then raise exception 'The expense was removed, cancelled or superseded.' using errcode='40001'; end if;
    if line->>'fundingOrigin'='SupplementalDraft' or (nullif(line->>'supplementUid','') is not null and line->>'supplementStatus' is distinct from 'APPROVED') then raise exception 'The supplemental expense is not approved.' using errcode='42501'; end if;
    baseline:=p_base->'stages'->item_id->stage_value;
    current_stage:=public.activity_financial_stage(before_parent,item_id,stage_value);
    if baseline is null or baseline->>'source' is distinct from current_stage->>'source' then raise exception 'Financial entry storage changed. Reopen before saving.' using errcode='40001'; end if;
    table_name:=case when stage_value='obligation' then 'financial_obligations' else 'financial_disbursements' end;
    date_column:=case when stage_value='obligation' then 'obligation_date' else 'disbursement_date' end;
    maps:='{}';
    if baseline->>'source'='legacy' then
      if baseline is distinct from current_stage then raise exception 'The legacy actuals changed. Reopen before saving.' using errcode='40001'; end if;
      -- Materialize every original legacy entry once, preserving duplicates/amounts.
      for entry in select value from jsonb_array_elements(baseline->'entries') loop
        entry_date:=nullif(entry->>'date','');
        if entry_date is null then
          select nullif(value->'value'->>'date','') into entry_date from jsonb_array_elements(edit->'operations')
            where value->>'action'='update' and value->>'id'=entry->>'id';
        end if;
        if entry_date is null then raise exception 'A legacy entry needs its actual date before this stage can be saved.'; end if;
        execute format('insert into public.%I(entity_type,parent_id,item_id,%I,amount,remarks) values(''activity_expense'',$1,$2,$3::date,$4,$5) returning id',table_name,date_column)
          into new_id using parent.id,item_id,entry_date,(entry->>'amount')::numeric,entry->>'remarks';
        maps:=maps||jsonb_build_object(entry->>'id',new_id);
      end loop;
    end if;
    if exists(select 1 from jsonb_array_elements(edit->'operations') o group by o->>'id' having count(*)>1) then raise exception 'Duplicate entry operations.'; end if;
    for op in select value from jsonb_array_elements(edit->'operations') loop
      if op->>'action' is null or op->>'action' not in ('insert','update','delete') then raise exception 'Unknown financial operation.'; end if;
      previous:=null;
      select value into previous from jsonb_array_elements(baseline->'entries') where value->>'id'=op->>'id';
      if op->>'action'='insert' then
        if previous is not null or nullif(op->>'id','') is null then raise exception 'New entries require a fresh local identity.'; end if;
      else
        if previous is null then raise exception 'The edited financial entry is not in the baseline.'; end if;
        if baseline->>'source'='central' then
          select value into entry from jsonb_array_elements(current_stage->'entries') where value->>'id'=op->>'id';
          if entry is distinct from previous then raise exception 'This financial entry changed or was removed while editing. Your draft was not saved.' using errcode='40001'; end if;
          entry_id:=(previous->>'id')::bigint;
        else entry_id:=(maps->>(previous->>'id'))::bigint; end if;
      end if;
      if op->>'action'='delete' then
        if coalesce((op->>'explicit')::boolean,false) is not true then raise exception 'An explicit removal action is required. Missing entries are never deleted automatically.'; end if;
        execute format('delete from public.%I where id=$1 and entity_type=''activity_expense'' and parent_id=$2 and item_id::text=$3',table_name) using entry_id,parent.id,item_id;
      else
        intended:=op->'value'; entry_date:=nullif(intended->>'date',''); entry_amount:=(intended->>'amount')::numeric;
        if entry_date is null or entry_amount is null or entry_amount=0 or entry_amount::text in ('NaN','Infinity','-Infinity') or (stage_value='disbursement' and entry_amount<0) then raise exception 'Every entry requires a valid date and amount.'; end if;
        if stage_value='obligation' and entry_amount<0 and nullif(btrim(intended->>'remarks'),'') is null then raise exception 'A reason is required for negative obligations.'; end if;
        if previous is null or left(coalesce(previous->>'date',''),7)<>left(entry_date,7) then perform public.check_activity_accomplishment_policy(actor,parent,'editFinancialAccomplishment',entry_date,p_reason); end if;
        if op->>'action'='insert' then
          execute format('insert into public.%I(entity_type,parent_id,item_id,%I,amount,remarks) values(''activity_expense'',$1,$2,$3::date,$4,$5) returning id',table_name,date_column)
            into new_id using parent.id,item_id,entry_date,entry_amount,coalesce(intended->>'remarks','');
        else
          execute format('update public.%I set %I=$1::date,amount=$2,remarks=$3 where id=$4 and entity_type=''activity_expense'' and parent_id=$5 and item_id::text=$6',table_name,date_column)
            using entry_date,entry_amount,coalesce(intended->>'remarks',''),entry_id,parent.id,item_id;
        end if;
      end if;
    end loop;
    insert into public.activity_financial_entry_state values(parent.id,item_id,stage_value) on conflict do nothing;
    changed_stages:=changed_stages||jsonb_build_object(item_id||':'||stage_value,jsonb_build_object('itemId',item_id,'stage',stage_value));
    before_changes:=before_changes||jsonb_build_array(jsonb_build_object('itemId',item_id,'stage',stage_value,'before',current_stage));
    touched:=true;
  end loop;
  for field,physical_value in select * from jsonb_each(p_physical) loop
    if field not in ('actualDate','actualEndDate','actualParticipantsMale','actualParticipantsFemale','actualPWD','actualMuslim','actualLGBTQ','actualSoloParent','actualSenior','actualYouth') then raise exception 'Only explicit physical accomplishment fields may be edited.'; end if;
    if p_surface<>'activity' then raise exception 'Financial ACF cannot change physical fields.' using errcode='42501'; end if;
    perform public.check_activity_accomplishment_policy(actor,parent,'editPhysicalAccomplishment',null,p_reason);
    physical_before:=coalesce(nullif(p_base->'activity'->field,'null'::jsonb),case when field in ('actualDate','actualEndDate') then 'null'::jsonb else '0'::jsonb end);
    physical_current:=coalesce(nullif(before_parent->field,'null'::jsonb),case when field in ('actualDate','actualEndDate') then 'null'::jsonb else '0'::jsonb end);
    if physical_before is distinct from physical_current then raise exception 'Physical accomplishments changed. Reopen before saving.' using errcode='40001'; end if;
    physical_audit_before:=physical_audit_before||jsonb_build_object(field,physical_current);
    if field in ('actualDate','actualEndDate') then
      if physical_value<>'null'::jsonb then perform public.check_activity_accomplishment_policy(actor,parent,'editPhysicalAccomplishment',physical_value#>>'{}',p_reason); end if;
    elsif (physical_value#>>'{}')::numeric<0 or (physical_value#>>'{}')::numeric<>trunc((physical_value#>>'{}')::numeric) then raise exception 'Actual participant counts must be non-negative whole numbers.'; end if;
    before_parent:=before_parent||jsonb_build_object(field,physical_value); touched:=true;
  end loop;
  if p_physical<>'{}'::jsonb then
    before_parent:=before_parent||jsonb_build_object('physical_accomplishment_submitted_at',case when nullif(before_parent->>'actualDate','') is not null then clock_timestamp() else null end);
    if p_physical ? 'actualDate' and p_physical->'actualDate'<>'null'::jsonb then before_parent:=before_parent||jsonb_build_object('status','Completed'); end if;
  end if;
  output_lines:='[]';
  for line in select value from jsonb_array_elements(coalesce(nullif(parent.expenses,'null'::jsonb),'[]'::jsonb)) loop
    item_id:=line->>'id';
    if target_edits ? item_id then line:=line||(target_edits->item_id); end if;
    foreach stage_value in array array['obligation','disbursement'] loop
      if not(changed_stages ? (item_id||':'||stage_value)) then continue; end if;
      current_stage:=public.activity_financial_stage(to_jsonb(parent),item_id,stage_value); stage_rows:=current_stage->'entries';
      select coalesce(sum((v->>'amount')::numeric),0),max(nullif(v->>'date','')) into total,last_date from jsonb_array_elements(stage_rows) v;
      if stage_value='obligation' then
        line:=line||jsonb_build_object('obligations',stage_rows,'actualObligationAmount',total,'actualObligationDate',last_date);
        if line ? 'actualAmount' then line:=line||jsonb_build_object('actualAmount',total); end if;
      else line:=line||jsonb_build_object('disbursements',stage_rows,'actualDisbursementAmount',total,'actualDisbursementDate',last_date); end if;
      after_changes:=after_changes||jsonb_build_array(jsonb_build_object('itemId',item_id,'stage',stage_value,'after',current_stage));
    end loop;
    output_lines:=output_lines||jsonb_build_array(line);
  end loop;
  if touched then
    parent:=jsonb_populate_record(parent,before_parent||jsonb_build_object('expenses',case when changed_stages<>'{}'::jsonb or target_edits<>'{}'::jsonb then output_lines else parent.expenses end));
    update public.activities set expenses=parent.expenses,"actualDate"=parent."actualDate","actualEndDate"=parent."actualEndDate",
      "actualParticipantsMale"=parent."actualParticipantsMale","actualParticipantsFemale"=parent."actualParticipantsFemale",
      "actualPWD"=parent."actualPWD","actualMuslim"=parent."actualMuslim","actualLGBTQ"=parent."actualLGBTQ","actualSoloParent"=parent."actualSoloParent","actualSenior"=parent."actualSenior","actualYouth"=parent."actualYouth",
      status=parent.status,physical_accomplishment_submitted_at=parent.physical_accomplishment_submitted_at,
      history=coalesce(parent.history,'[]'::jsonb)||jsonb_build_array(jsonb_build_object('date',clock_timestamp(),'event','Updated accomplishment','user',actor."fullName")),updated_at=clock_timestamp()
      where id=parent.id returning * into parent;
    insert into public.activity_accomplishment_revisions(activity_id,actor_id,request_key,reason,changes)
      values(parent.id,actor.id,p_request_key,nullif(btrim(p_reason),''),jsonb_build_object('before',before_changes,'after',after_changes,'physicalBefore',physical_audit_before,'physicalChanges',p_physical,'targetChanges',p_targets));
  end if;
  result:=public.activity_accomplishment_snapshot(to_jsonb(parent));
  insert into public.activity_accomplishment_requests values(p_request_key,parent.id,actor.id,fingerprint,result,now());
  return result;
end; $$;

