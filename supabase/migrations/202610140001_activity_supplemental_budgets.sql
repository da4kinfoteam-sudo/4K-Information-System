create or replace function public.activity_expense_plan(p_line jsonb) returns jsonb
language sql immutable set search_path=public,pg_temp as $$
  select jsonb_build_object('id',p_line->'id','objectType',p_line->'objectType','expenseParticular',p_line->'expenseParticular',
    'uacsCode',p_line->'uacsCode','amount',p_line->'amount','obligationMonth',p_line->'obligationMonth','disbursementMonth',p_line->'disbursementMonth',
    'budgetItemGroupId',p_line->'budgetItemGroupId','isCancelled',p_line->'isCancelled','isSavings',p_line->'isSavings','isRealignment',p_line->'isRealignment',
    'fundingOrigin',p_line->'fundingOrigin','supplementUid',p_line->'supplementUid','supplementStatus',p_line->'supplementStatus',
    'supplementalSource',p_line->'supplementalSource','supplementRevisionPending',p_line->'supplementRevisionPending');
$$;
create or replace function public.activity_original_plan(p_lines jsonb) returns jsonb
language sql immutable set search_path=public,pg_temp as $$
  select coalesce(jsonb_agg(public.activity_expense_plan(value) order by value->>'id'),'[]'::jsonb)
  from jsonb_array_elements(coalesce(p_lines,'[]'::jsonb))
  where coalesce(value->>'fundingOrigin','') not in ('Supplemental','SupplementalDraft') and nullif(value->>'supplementUid','') is null;
$$;
create or replace function public.activity_budget_baseline(p_record jsonb,p_kind text,p_reason text default null) returns jsonb
language sql stable set search_path=public,pg_temp as $$
  select jsonb_build_object('capturedAt',now(),'kind',p_kind,'reason',p_reason,'expenses',
    case when coalesce((p_record->>'isSavings')::boolean,false) or coalesce((p_record->>'isRealignment')::boolean,false)
      or coalesce((p_record->>'isTransferTargetExcluded')::boolean,false) then '[]'::jsonb else
    (select coalesce(jsonb_agg(public.activity_expense_plan(value) order by value->>'id'),'[]'::jsonb)
     from jsonb_array_elements(coalesce(p_record->'expenses','[]'::jsonb))
     where coalesce(value->>'fundingOrigin','') not in ('Supplemental','SupplementalDraft') and nullif(value->>'supplementUid','') is null
       and not coalesce((value->>'isCancelled')::boolean,false) and not coalesce((value->>'isSavings')::boolean,false) and not coalesce((value->>'isRealignment')::boolean,false)) end);
$$;

create or replace function public.activity_supplement_actor(p_actor_id bigint,p_password text,p_activity_id bigint,p_write boolean default false)
returns public.users language plpgsql security definer set search_path=public,pg_temp as $$
declare a public.users%rowtype; r public.roles_config%rowtype; item public.activities%rowtype; v jsonb; scope text; allowed boolean; rules jsonb;
begin
  select * into a from public.users where id=p_actor_id;
  if a.id is null then raise exception 'Your session could not be verified.' using errcode='42501'; end if;
  if auth.uid() is not null then
    if a.auth_id is distinct from auth.uid() then raise exception 'Your session does not match this request.' using errcode='42501'; end if;
  elsif nullif(p_password,'') is null or a.password is distinct from p_password then
    raise exception 'Your session could not be verified.' using errcode='42501';
  end if;
  select * into r from public.roles_config where role=a.role and module='Activities' limit 1;
  v:=a.permissions_override->'Activities'->case when p_write then 'can_edit' else 'can_view' end;
  allowed:=case when a.role in ('Super Admin','Administrator') then true when p_write and a.role='Guest' then false
    when jsonb_typeof(v)='boolean' then (v#>>'{}')::boolean else case when p_write then coalesce(r.can_edit,false) else coalesce(r.can_view,true) end end;
  if not allowed then raise exception 'Activities permission is required.' using errcode='42501'; end if;
  select * into item from public.activities where id=p_activity_id;
  if item.id is null then raise exception 'The Activity is no longer available.' using errcode='P0002'; end if;
  scope:=case when a.visibility_scope in ('All OUs','Own OU') then a.visibility_scope when r.visibility_scope in ('All OUs','Own OU') then r.visibility_scope
    when a.role in ('Super Admin','Administrator','Management') then 'All OUs' else 'Own OU' end;
  if scope='Own OU' and item."operatingUnit" is distinct from a."operatingUnit" then raise exception 'This Activity is outside your OU scope.' using errcode='42501'; end if;
  if p_write then
    if item.status='Cancelled' or (item."budgetItemTransferId" is not null and item.workflow_status is distinct from 'APPROVED') then
      raise exception 'This Activity cannot receive supplemental changes.' using errcode='55000';
    end if;
    select settings into rules from public.dcf_policy_settings where settings_key='dcf_editing_policy';
    v:=rules->'roleRules'->a.role->'activities'->item.status->'editSupplementalBudget';
    allowed:=case when jsonb_typeof(v)='boolean' then (v#>>'{}')::boolean
      else a.role<>'Guest' and (item.status in ('Proposed','Ongoing') or a.role in ('Super Admin','Administrator')) end;
    if not allowed then raise exception 'Supplemental editing is disabled for this role and status.' using errcode='42501'; end if;
  end if;
  return a;
end; $$;

create or replace function public.read_activity_supplements(p_actor_id bigint,p_actor_password text,p_activity_id bigint,p_history boolean default false)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
begin
  perform public.activity_supplement_actor(p_actor_id,p_actor_password,p_activity_id,false);
  return jsonb_build_object('activity',(select to_jsonb(a) from public.activities a where id=p_activity_id),
    'supplements',(select coalesce(jsonb_agg(to_jsonb(s) order by created_at),'[]'::jsonb) from public.activity_supplements s where activity_id=p_activity_id),
    'revisions',case when p_history then (select coalesce(jsonb_agg(to_jsonb(h) order by created_at desc),'[]'::jsonb)
      from (select id,activity_id,supplement_uid,actor_id,operation,reason,created_at from public.activity_supplement_revisions where activity_id=p_activity_id order by created_at desc limit 50) h) else '[]'::jsonb end);
end; $$;

create or replace function public.guard_activity_budget_separation() returns trigger
language plpgsql security definer set search_path=public,pg_temp as $$
declare line jsonb; previous jsonb; ledger public.activity_supplements%rowtype; trusted boolean;
begin
  trusted:=coalesce(current_setting('app.activity_supplement_write',true),'')='on';
  if current_setting('app.allow_budget_item_transfer_resolution',true)='on' then
    if tg_op='INSERT' then
      new.original_budget_snapshot:=public.activity_budget_baseline(to_jsonb(new),'initial');
      for line in select value from jsonb_array_elements(coalesce(new.expenses,'[]'::jsonb)) loop
        if line->>'fundingOrigin'='SupplementalDraft' then raise exception 'Unsubmitted supplemental drafts cannot be transferred.' using errcode='55000'; end if;
        if nullif(line->>'supplementUid','') is not null and not exists(select 1 from public.activity_supplements where uid=(line->>'supplementUid')::uuid and status='APPROVED' and pending_proposal is null) then
          raise exception 'Resolve supplemental approval or revisions before transferring.' using errcode='55000'; end if;
      end loop;
    end if;
    return new;
  end if;
  if tg_op='UPDATE' then
    if old.original_budget_snapshot is not null and new.original_budget_snapshot is distinct from old.original_budget_snapshot then
      raise exception 'The frozen original allocation cannot be changed.' using errcode='42501';
    end if;
    if not trusted and new.original_budget_snapshot is distinct from old.original_budget_snapshot then raise exception 'Use the authorized baseline operation.' using errcode='42501'; end if;
    if old.status<>'Proposed' or old.original_budget_snapshot is not null then
      if public.activity_original_plan(new.expenses) is distinct from public.activity_original_plan(old.expenses)
        or new."fundingYear" is distinct from old."fundingYear" or new."fundType" is distinct from old."fundType"
        or new.tier is distinct from old.tier or new."fundSourceUid" is distinct from old."fundSourceUid"
        or new."isSavings" is distinct from old."isSavings" or new."isRealignment" is distinct from old."isRealignment" then
        raise exception 'The original budget is locked. Use Supplemental Information for additional funding.' using errcode='42501';
      end if;
    end if;
    if not trusted and exists(select 1 from jsonb_array_elements(coalesce(old.expenses,'[]'::jsonb)) x
      where nullif(x->>'supplementUid','') is not null and not exists(select 1 from jsonb_array_elements(coalesce(new.expenses,'[]'::jsonb)) y where y->>'id'=x->>'id')) then
      raise exception 'Supplemental expense rows cannot be removed by an ordinary save.' using errcode='42501';
    end if;
  elsif new.original_budget_snapshot is not null then raise exception 'Original allocation cannot be supplied on insertion.' using errcode='42501';
  end if;
  if not trusted then
    if tg_op='INSERT' and (coalesce(new."isSavings",false) or coalesce(new."isRealignment",false)) then raise exception 'Use Supplemental Information for new Savings or Realignment funding.' using errcode='42501'; end if;
    if tg_op='UPDATE' and (new."isSavings" is distinct from old."isSavings" or new."isRealignment" is distinct from old."isRealignment") then raise exception 'Whole-Activity funding classification cannot be changed through ordinary editing.' using errcode='42501'; end if;
  end if;
  for line in select value from jsonb_array_elements(coalesce(new.expenses,'[]'::jsonb)) loop
    previous:=null;
    if tg_op='UPDATE' then select value into previous from jsonb_array_elements(coalesce(old.expenses,'[]'::jsonb)) where value->>'id'=line->>'id'; end if;
    if not trusted and nullif(previous->>'supplementUid','') is not null and public.activity_expense_plan(previous) is distinct from public.activity_expense_plan(line) then
      raise exception 'Supplemental funding must be changed through the authorized operation.' using errcode='42501'; end if;
    if not trusted and coalesce(line->>'fundingOrigin','') not in ('Supplemental','SupplementalDraft') and
      ((coalesce((line->>'isSavings')::boolean,false) and not coalesce((previous->>'isSavings')::boolean,false)) or
       (coalesce((line->>'isRealignment')::boolean,false) and not coalesce((previous->>'isRealignment')::boolean,false))) then
      raise exception 'Add new Savings or Realignment funding through Supplemental Information.' using errcode='42501'; end if;
    if nullif(line->>'supplementUid','') is not null then
      select * into ledger from public.activity_supplements where uid=(line->>'supplementUid')::uuid and activity_id=new.id;
      if ledger.uid is null or line->>'supplementStatus' is distinct from ledger.status or line->>'supplementalSource' is distinct from ledger.source
        or line->>'fundingOrigin' is distinct from 'Supplemental' then raise exception 'Invalid supplemental classification.' using errcode='42501'; end if;
      previous:=null;
      if tg_op='UPDATE' then select value into previous from jsonb_array_elements(coalesce(old.expenses,'[]'::jsonb)) where value->>'id'=line->>'id'; end if;
      if not trusted and (previous is null or public.activity_expense_plan(previous) is distinct from public.activity_expense_plan(line)) then
        raise exception 'Use Supplemental Information to change supplemental funding.' using errcode='42501';
      end if;
      if ledger.status<>'APPROVED' and (coalesce((line->>'actualObligationAmount')::numeric,0)<>0 or coalesce((line->>'actualDisbursementAmount')::numeric,0)<>0
        or jsonb_array_length(coalesce(line->'obligations','[]'::jsonb))>0 or jsonb_array_length(coalesce(line->'disbursements','[]'::jsonb))>0) then
        raise exception 'Unapproved supplements cannot contain actuals.' using errcode='42501';
      end if;
    elsif line->>'fundingOrigin'='Supplemental' then raise exception 'A supplement UID is required.' using errcode='42501';
    elsif line->>'fundingOrigin'='SupplementalDraft' then
      if not trusted and tg_op='UPDATE' and (previous is null or previous->>'fundingOrigin' is distinct from 'SupplementalDraft') then
        raise exception 'Use Supplemental Information to add or reclassify supplemental funding.' using errcode='42501'; end if;
      if coalesce(line->>'supplementStatus','DRAFT')<>'DRAFT' then raise exception 'Unsubmitted supplemental drafts cannot be approved.' using errcode='42501'; end if;
      if coalesce((line->>'actualObligationAmount')::numeric,0)<>0 or coalesce((line->>'actualDisbursementAmount')::numeric,0)<>0
        or jsonb_array_length(coalesce(line->'obligations','[]'::jsonb))>0 or jsonb_array_length(coalesce(line->'disbursements','[]'::jsonb))>0 then
        raise exception 'Unsubmitted supplemental drafts cannot contain actuals.' using errcode='42501'; end if;
    elsif tg_op='UPDATE' then
      select value into previous from jsonb_array_elements(coalesce(old.expenses,'[]'::jsonb)) where value->>'id'=line->>'id';
      if previous is not null and nullif(previous->>'supplementUid','') is not null then raise exception 'Supplemental classification cannot be cleared.' using errcode='42501'; end if;
    end if;
  end loop;
  if new.original_budget_snapshot is null and new.status in ('Ongoing','Completed') and coalesce(new.workflow_status,'APPROVED')='APPROVED' then
    if tg_op='INSERT' then new.original_budget_snapshot:=public.activity_budget_baseline(to_jsonb(new),'initial');
    elsif old.status='Proposed' or coalesce(old.workflow_status,'APPROVED')<>'APPROVED' then new.original_budget_snapshot:=public.activity_budget_baseline(to_jsonb(new),'initial'); end if;
  end if;
  return new;
end; $$;
drop trigger if exists guard_activity_budget_separation on public.activities;
create trigger guard_activity_budget_separation before insert or update on public.activities for each row execute function public.guard_activity_budget_separation();

create or replace function public.guard_activity_supplement_delete() returns trigger
language plpgsql security definer set search_path=public,pg_temp as $$
begin
  if old.original_budget_snapshot is not null or exists(select 1 from public.activity_supplements where activity_id=old.id)
    or exists(select 1 from public.activity_supplement_revisions where activity_id=old.id) then
    raise exception 'Frozen or supplemental budget history must be retained. This Activity cannot be deleted.' using errcode='55000';
  end if;
  return old;
end; $$;
drop trigger if exists guard_activity_supplement_delete on public.activities;
create trigger guard_activity_supplement_delete before delete on public.activities for each row execute function public.guard_activity_supplement_delete();

create or replace function public.guard_activity_supplement_actual() returns trigger
language plpgsql security definer set search_path=public,pg_temp as $$
declare line jsonb; item public.activities%rowtype;
begin
  if new.entity_type<>'activity_expense' then return new; end if;
  select * into item from public.activities where id=new.parent_id;
  select value into line from jsonb_array_elements(coalesce(item.expenses,'[]'::jsonb)) where value->>'id'=new.item_id::text;
  if line->>'fundingOrigin' in ('Supplemental','SupplementalDraft') or nullif(line->>'supplementUid','') is not null then
    if item."budgetItemTransferId" is not null and item.workflow_status is distinct from 'APPROVED' then raise exception 'The transfer is not approved.' using errcode='42501'; end if;
    if not exists(select 1 from public.activity_supplements where uid=nullif(line->>'supplementUid','')::uuid and activity_id=new.parent_id and status='APPROVED') then
      raise exception 'Supplemental funding must be approved before recording actuals.' using errcode='42501'; end if;
  end if;
  return new;
end; $$;
drop trigger if exists guard_activity_supplement_actual on public.financial_obligations;
create trigger guard_activity_supplement_actual before insert or update on public.financial_obligations for each row execute function public.guard_activity_supplement_actual();
drop trigger if exists guard_activity_supplement_actual on public.financial_disbursements;
create trigger guard_activity_supplement_actual before insert or update on public.financial_disbursements for each row execute function public.guard_activity_supplement_actual();

create or replace function public.save_activity_supplement(
  p_actor_id bigint,p_actor_password text,p_activity_id bigint,p_uid uuid,p_operation text,
  p_source text,p_reference text,p_authorization_date date,p_reason text,p_rows jsonb,
  p_expected_revision integer,p_expected_updated_at timestamptz,p_establish_baseline boolean,p_request_key uuid
) returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare
  actor public.users%rowtype; parent public.activities%rowtype; ledger public.activity_supplements%rowtype;
  cached public.activity_supplement_requests%rowtype; request_hash text; before_state jsonb; proposal jsonb;
  rows jsonb:=coalesce(p_rows,'[]'::jsonb); result_rows jsonb:='[]'::jsonb; previous_rows jsonb; remaining jsonb;
  line jsonb; previous jsonb; checked_row jsonb; old_actual jsonb; committed numeric; paid numeric; amount numeric;
  new_status text; action text:=p_operation; source_value text:=p_source; reference_value text:=btrim(coalesce(p_reference,''));
  date_value date:=p_authorization_date; reason_value text:=btrim(coalesce(p_reason,'')); expense_id text; previous_key text;
  pending_revision boolean:=false; remove_rows boolean:=false; row_has_actuals boolean; supplied_ids text[];
begin
  if p_request_key is null or p_uid is null or action is null or p_expected_revision is null or p_expected_revision<0 or action not in ('draft','submit','approve','reject','withdraw','delete','baseline') then raise exception 'Invalid supplemental request.' using errcode='22023'; end if;
  actor:=public.activity_supplement_actor(p_actor_id,p_actor_password,p_activity_id,false);
  request_hash:=md5(jsonb_build_object('activity',p_activity_id,'uid',p_uid,'operation',action,'source',p_source,'reference',p_reference,
    'date',p_authorization_date,'reason',p_reason,'rows',p_rows,'revision',p_expected_revision,'updated',p_expected_updated_at,'baseline',p_establish_baseline)::text);
  perform pg_advisory_xact_lock(hashtextextended(p_request_key::text,0));
  select * into cached from public.activity_supplement_requests where request_key=p_request_key;
  if cached.request_key is not null then
    if cached.actor_id<>actor.id or cached.activity_id<>p_activity_id or cached.request_hash<>request_hash then raise exception 'This retry key belongs to a different request.' using errcode='22023'; end if;
    return public.read_activity_supplements(p_actor_id,p_actor_password,p_activity_id);
  end if;
  actor:=public.activity_supplement_actor(p_actor_id,p_actor_password,p_activity_id,true);
  select * into parent from public.activities where id=p_activity_id for update;
  if parent.updated_at is distinct from p_expected_updated_at then raise exception 'The Activity changed. Reload before applying this draft.' using errcode='40001'; end if;
  if reason_value='' then raise exception 'A reason is required.' using errcode='22023'; end if;
  perform set_config('app.activity_supplement_write','on',true);
  if parent.original_budget_snapshot is null and parent.status<>'Proposed' then
    if not p_establish_baseline or actor.role not in ('Super Admin','Administrator') then raise exception 'An administrator must explicitly establish the current original-plan baseline first.' using errcode='42501'; end if;
    update public.activities set original_budget_snapshot=public.activity_budget_baseline(to_jsonb(parent),'legacy_confirmed',reason_value),updated_at=clock_timestamp() where id=parent.id returning * into parent;
    insert into public.activity_supplement_revisions(activity_id,actor_id,operation,reason,after_snapshot) values(parent.id,actor.id,'baseline',reason_value,parent.original_budget_snapshot);
  end if;
  if action='baseline' then
    if actor.role not in ('Super Admin','Administrator') then raise exception 'An administrator must establish the baseline.' using errcode='42501'; end if;
    if parent.status='Proposed' then raise exception 'Proposed plans remain editable and do not need a legacy baseline.' using errcode='55000'; end if;
    insert into public.activity_supplement_requests values(p_request_key,actor.id,parent.id,request_hash,now());
    return public.read_activity_supplements(p_actor_id,p_actor_password,p_activity_id);
  end if;
  select * into ledger from public.activity_supplements where uid=p_uid for update;
  if ledger.uid is not null and ledger.activity_id<>parent.id then raise exception 'The supplement belongs to another Activity.' using errcode='42501'; end if;
  if coalesce(ledger.revision,0)<>p_expected_revision then raise exception 'The supplement changed. Reload before applying this draft.' using errcode='40001'; end if;
  select coalesce(jsonb_agg(value),'[]'::jsonb) into previous_rows from jsonb_array_elements(coalesce(parent.expenses,'[]'::jsonb)) where value->>'supplementUid'=p_uid::text;
  before_state:=case when ledger.uid is null then null else jsonb_build_object('ledger',to_jsonb(ledger),'rows',previous_rows) end;
  if action in ('approve','reject') then
    if ledger.uid is null then raise exception 'Supplement not found.' using errcode='P0002'; end if;
    if actor.role not in ('Super Admin','Administrator','Focal - User','Management')
      or (ledger.approver_id is not null and ledger.approver_id<>actor.id) then raise exception 'You are not the permitted approver.' using errcode='42501'; end if;
    if ledger.status<>'PENDING' and ledger.pending_status is distinct from 'PENDING' then raise exception 'There is no pending supplement to resolve.' using errcode='55000'; end if;
    if action='reject' then
      if ledger.status='APPROVED' then
        update public.activity_supplements set pending_proposal=null,pending_status=null,revision=revision+1,updated_at=clock_timestamp() where uid=p_uid returning * into ledger;
        update public.activities set expenses=(select coalesce(jsonb_agg(case when value->>'supplementUid'=p_uid::text then value||jsonb_build_object('supplementRevisionPending',false) else value end),'[]'::jsonb) from jsonb_array_elements(expenses)),updated_at=clock_timestamp() where id=parent.id;
      else
        update public.activity_supplements set status='REJECTED',revision=revision+1,updated_at=clock_timestamp() where uid=p_uid returning * into ledger;
        update public.activities set expenses=(select coalesce(jsonb_agg(case when value->>'supplementUid'=p_uid::text then value||jsonb_build_object('supplementStatus','REJECTED') else value end),'[]'::jsonb) from jsonb_array_elements(expenses)),updated_at=clock_timestamp() where id=parent.id;
      end if;
      insert into public.activity_supplement_revisions(activity_id,supplement_uid,actor_id,operation,reason,before_snapshot,after_snapshot) values(parent.id,p_uid,actor.id,'reject',reason_value,before_state,to_jsonb(ledger));
      insert into public.activity_supplement_requests values(p_request_key,actor.id,parent.id,request_hash,now());
      return public.read_activity_supplements(p_actor_id,p_actor_password,p_activity_id);
    end if;
    if ledger.pending_proposal is not null then
      proposal:=ledger.pending_proposal; action:=proposal->>'operation'; rows:=proposal->'rows';
      source_value:=proposal->>'source'; reference_value:=proposal->>'reference'; date_value:=(proposal->>'date')::date;
    else rows:=previous_rows; source_value:=ledger.source; reference_value:=ledger.reference; date_value:=ledger.authorization_date; end if;
    new_status:=case when action='withdraw' then 'WITHDRAWN' else 'APPROVED' end;
  else
    if ledger.status='WITHDRAWN' then raise exception 'Withdrawn supplements cannot be reopened.' using errcode='55000'; end if;
    if action='delete' and ledger.status not in ('DRAFT','REJECTED') then raise exception 'Only unapproved drafts may be deleted.' using errcode='55000'; end if;
    if ledger.pending_status='PENDING' then raise exception 'Resolve the pending revision before editing again.' using errcode='55000'; end if;
    pending_revision:=ledger.status='APPROVED' and (action='draft' or coalesce(actor.requires_approver,false));
    new_status:=case when action in ('delete','withdraw') then 'WITHDRAWN' when action='draft' then 'DRAFT'
      when coalesce(actor.requires_approver,false) then 'PENDING' else 'APPROVED' end;
    if pending_revision then new_status:='APPROVED'; end if;
  end if;
  if source_value not in ('Savings','Realignment') then raise exception 'Select Savings or Realignment.' using errcode='22023'; end if;
  if action not in ('draft','delete') and (reference_value='' or date_value is null) then raise exception 'Authorization reference and date are required.' using errcode='22023'; end if;
  if action in ('withdraw','delete') then rows:=previous_rows; remove_rows:=action='delete'; end if;
  if jsonb_typeof(rows)<>'array' or jsonb_array_length(rows)=0 then raise exception 'Add at least one expense schedule.' using errcode='22023'; end if;
  select array_agg(value->>'id') into supplied_ids from jsonb_array_elements(rows);
  if cardinality(supplied_ids)<>(select count(distinct id) from unnest(supplied_ids) id) then raise exception 'Expense IDs must be unique.' using errcode='22023'; end if;
  for line in select value from jsonb_array_elements(rows) loop
    expense_id:=line->>'id';
    if expense_id is null or expense_id !~ '^-?[0-9]+$' then raise exception 'Invalid expense identity.' using errcode='22023'; end if;
    select value into previous from jsonb_array_elements(coalesce(parent.expenses,'[]'::jsonb)) where value->>'id'=expense_id;
    if previous is not null and coalesce(previous->>'supplementUid','')<>p_uid::text and previous->>'fundingOrigin' is distinct from 'SupplementalDraft' then
      raise exception 'An original or different supplemental expense cannot be reclassified.' using errcode='42501'; end if;
    amount:=(line->>'amount')::numeric;
    if amount is null or amount<=0 or amount::text in ('NaN','Infinity','-Infinity') then raise exception 'Schedule amounts must be finite and positive.' using errcode='22023'; end if;
    if coalesce(line->>'obligationMonth','') !~ '^\d{4}-\d{2}-\d{2}$' or coalesce(line->>'disbursementMonth','') !~ '^\d{4}-\d{2}-\d{2}$' then raise exception 'Select valid schedule months.' using errcode='22023'; end if;
    perform (line->>'obligationMonth')::date; perform (line->>'disbursementMonth')::date;
    if not (previous is not null and previous->>'objectType'=line->>'objectType' and previous->>'expenseParticular'=line->>'expenseParticular' and previous->>'uacsCode'=line->>'uacsCode')
      and not exists(select 1 from public.reference_uacs where "objectType"=line->>'objectType' and particular=line->>'expenseParticular' and "uacsCode"=line->>'uacsCode') then
      raise exception 'Select a listed UACS reference.' using errcode='22023'; end if;
    select coalesce(sum(f.amount),case when jsonb_array_length(coalesce(previous->'obligations','[]'::jsonb))>0 then
      (select coalesce(sum((v->>'amount')::numeric),0) from jsonb_array_elements(previous->'obligations') v) else coalesce((previous->>'actualObligationAmount')::numeric,0) end)
      into committed from public.financial_obligations f where f.entity_type='activity_expense' and f.parent_id=parent.id and f.item_id::text=expense_id;
    select coalesce(sum(f.amount),case when jsonb_array_length(coalesce(previous->'disbursements','[]'::jsonb))>0 then
      (select coalesce(sum((v->>'amount')::numeric),0) from jsonb_array_elements(previous->'disbursements') v) else coalesce((previous->>'actualDisbursementAmount')::numeric,0) end)
      into paid from public.financial_disbursements f where f.entity_type='activity_expense' and f.parent_id=parent.id and f.item_id::text=expense_id;
    row_has_actuals:=jsonb_array_length(coalesce(previous->'obligations','[]'::jsonb))>0 or jsonb_array_length(coalesce(previous->'disbursements','[]'::jsonb))>0
      or committed<>0 or paid<>0 or exists(select 1 from public.financial_obligations f where f.entity_type='activity_expense' and f.parent_id=parent.id and f.item_id::text=expense_id)
      or exists(select 1 from public.financial_disbursements f where f.entity_type='activity_expense' and f.parent_id=parent.id and f.item_id::text=expense_id);
    if amount<greatest(committed,paid,0) or (action in ('withdraw','delete') and row_has_actuals) then raise exception 'Committed or historical actuals prevent this reduction or withdrawal.' using errcode='55000'; end if;
    if previous is null and (jsonb_array_length(coalesce(line->'obligations','[]'::jsonb))>0 or jsonb_array_length(coalesce(line->'disbursements','[]'::jsonb))>0
      or coalesce((line->>'actualObligationAmount')::numeric,0)<>0 or coalesce((line->>'actualDisbursementAmount')::numeric,0)<>0) then raise exception 'New supplements cannot supply actuals.' using errcode='42501'; end if;
    checked_row:=coalesce(previous,'{}'::jsonb)||jsonb_build_object('id',line->'id','objectType',line->'objectType','expenseParticular',line->'expenseParticular','uacsCode',line->'uacsCode',
      'amount',amount,'obligationMonth',line->'obligationMonth','disbursementMonth',line->'disbursementMonth','budgetItemGroupId',line->'budgetItemGroupId',
      'fundingOrigin','Supplemental','supplementUid',p_uid,'supplementStatus',new_status,'supplementalSource',source_value,'supplementRevisionPending',false,
      'isSavings',source_value='Savings','isRealignment',source_value='Realignment','isCancelled',false,'adjustmentReason',reason_value);
    result_rows:=result_rows||jsonb_build_array(checked_row);
  end loop;
  if ledger.status='APPROVED' and exists(select 1 from jsonb_array_elements(previous_rows) old_line where not (old_line->>'id'=any(supplied_ids))) then
    raise exception 'Use an explicit withdrawal rather than silently removing saved installment rows.' using errcode='55000'; end if;
  proposal:=jsonb_build_object('operation',action,'rows',result_rows,'source',source_value,'reference',reference_value,'date',date_value,'reason',reason_value);
  if ledger.uid is null then
    insert into public.activity_supplements(uid,activity_id,source,reference,authorization_date,reason,status,created_by,approver_id)
      values(p_uid,parent.id,source_value,reference_value,date_value,reason_value,new_status,actor.id,actor.approver_id) returning * into ledger;
  elsif pending_revision then
    update public.activity_supplements set pending_proposal=proposal,pending_status=case when p_operation='draft' then 'DRAFT' else 'PENDING' end,
      approver_id=actor.approver_id,revision=revision+1,updated_at=clock_timestamp() where uid=p_uid returning * into ledger;
  else
    update public.activity_supplements set source=source_value,reference=reference_value,authorization_date=date_value,reason=reason_value,status=new_status,
      pending_proposal=null,pending_status=null,revision=revision+1,updated_at=clock_timestamp() where uid=p_uid returning * into ledger;
  end if;
  if pending_revision then
    update public.activities set expenses=(select coalesce(jsonb_agg(case when value->>'supplementUid'=p_uid::text then value||jsonb_build_object('supplementRevisionPending',true) else value end),'[]'::jsonb) from jsonb_array_elements(expenses)),updated_at=clock_timestamp() where id=parent.id;
  else
    select coalesce(jsonb_agg(value),'[]'::jsonb) into remaining from jsonb_array_elements(coalesce(parent.expenses,'[]'::jsonb))
      where coalesce(value->>'supplementUid','')<>p_uid::text and not (coalesce(value->>'fundingOrigin','')='SupplementalDraft' and value->>'id'=any(supplied_ids));
    update public.activities set expenses=remaining||case when remove_rows then '[]'::jsonb else result_rows end,
      history=coalesce(history,'[]'::jsonb)||jsonb_build_array(jsonb_build_object('date',now(),'event','Supplemental funding '||p_operation,'user',actor."fullName",'supplementUid',p_uid,'reason',reason_value)),updated_at=clock_timestamp() where id=parent.id;
  end if;
  insert into public.activity_supplement_revisions(activity_id,supplement_uid,actor_id,operation,reason,before_snapshot,after_snapshot)
    values(parent.id,p_uid,actor.id,p_operation,reason_value,before_state,jsonb_build_object('ledger',to_jsonb(ledger),'rows',case when pending_revision then previous_rows else result_rows end));
  insert into public.activity_supplement_requests values(p_request_key,actor.id,parent.id,request_hash,now());
  return public.read_activity_supplements(p_actor_id,p_actor_password,p_activity_id);
end; $$;

create or replace function public.transfer_activity_supplement_lineage() returns trigger
language plpgsql security definer set search_path=public,pg_temp as $$
declare ledger public.activity_supplements%rowtype; transfer_record public.budget_item_transfers%rowtype; moved_uid uuid; old_uid uuid;
begin
  if pg_trigger_depth()>1 or current_setting('app.allow_budget_item_transfer_resolution',true) is distinct from 'on'
    or new.workflow_status is distinct from 'APPROVED' or not coalesce(new."isTransferTargetExcluded",false) then return new; end if;
  select * into transfer_record from public.budget_item_transfers where destination_id=new.id and source_type='activity' and status='pending' for update;
  if transfer_record.id is null then return new; end if;
  for old_uid in select distinct nullif(value->>'supplementUid','')::uuid from jsonb_array_elements(coalesce(new.expenses,'[]'::jsonb)) where nullif(value->>'supplementUid','') is not null loop
    select * into ledger from public.activity_supplements where uid=old_uid for update;
    if ledger.activity_id=new.id then continue; end if;
    if ledger.activity_id is distinct from transfer_record.source_id or ledger.status<>'APPROVED' or ledger.pending_proposal is not null then
      raise exception 'Supplemental lineage changed or has a pending revision. Resolve it before transferring.' using errcode='55000'; end if;
    if exists(select 1 from public.activities a,jsonb_array_elements(a.expenses) row_value where a.id=transfer_record.source_id and row_value->>'supplementUid'=old_uid::text) then
      moved_uid:=gen_random_uuid();
      insert into public.activity_supplements(uid,activity_id,source,reference,authorization_date,reason,status,created_by,approver_id,origin_uid)
        values(moved_uid,new.id,ledger.source,ledger.reference,ledger.authorization_date,ledger.reason,'APPROVED',ledger.created_by,ledger.approver_id,coalesce(ledger.origin_uid,old_uid));
    else
      moved_uid:=old_uid;
      update public.activity_supplements set activity_id=new.id,revision=revision+1,updated_at=clock_timestamp() where uid=old_uid;
    end if;
    perform set_config('app.activity_supplement_write','on',true);
    update public.activities set expenses=(select jsonb_agg(case when value->>'supplementUid'=old_uid::text then value||jsonb_build_object('supplementUid',moved_uid) else value end) from jsonb_array_elements(expenses)) where id=new.id;
    insert into public.activity_supplement_revisions(activity_id,supplement_uid,actor_id,operation,reason,before_snapshot,after_snapshot)
      values(new.id,moved_uid,transfer_record.actor_id,'transfer',transfer_record.reason,to_jsonb(ledger),jsonb_build_object('sourceActivity',transfer_record.source_id,'destinationActivity',new.id,'transferUid',transfer_record.id));
  end loop;
  return new;
end; $$;
drop trigger if exists transfer_activity_supplement_lineage on public.activities;
