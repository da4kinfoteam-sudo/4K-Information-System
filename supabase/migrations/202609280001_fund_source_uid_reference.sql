-- Introduce the global Fund Source reference and additive UID links for Subprojects.
-- Existing Fund Source text is retained; only the new UID column is backfilled.

create sequence if not exists public.ref_fund_source_uid_seq;

create table if not exists public.ref_fund_sources (
  id bigint generated by default as identity primary key,
  uid text not null unique,
  label text not null,
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null default auth.uid(),
  updated_by uuid references auth.users(id) on delete set null default auth.uid(),
  constraint ref_fund_sources_label_not_blank check (nullif(btrim(label), '') is not null)
);

alter table public.ref_fund_sources
  alter column uid drop default;

drop trigger if exists ref_fund_sources_assign_uid on public.ref_fund_sources;

create unique index if not exists ref_fund_sources_active_label_uidx
  on public.ref_fund_sources (lower(btrim(label)))
  where is_active;

